//! Opt-in password authentication over managed SSH against a local endpoint.
//!
//! This lane closes the gap left by the internal Docker fixture: it exercises
//! `SshIdentity::Password` through the real managed transport, but its peer is a
//! local `neotales-ssh` server on a loopback port. It needs no Docker Engine,
//! Docker socket, `sudo`, host account, registry, or external credential. The
//! host key and the password are generated for each run and vanish with the
//! temporary directory.
//!
//! The server is a conforming SSH peer, not a mock of this crate: the real
//! handshake, password user-authentication exchange, session channel, and
//! `docker system dial-stdio` exec request all run, and a complete Engine
//! `/_ping` answer travels back over the session. What it does not prove is
//! interoperability with OpenSSH's own password backend, which needs a host
//! account and is deliberately out of scope here.
//!
//! The peer is started only when `NEOTALES_DOCKER_SSH_PASSWORD_ENDPOINT=1`.
//! Both tests are ignored in the default gate. Opt in with:
//!
//! ```text
//! NEOTALES_DOCKER_SSH_PASSWORD_ENDPOINT=1 cargo test -p neotales-docker \
//!   --all-features --test managed_ssh_password_endpoint -- --ignored --test-threads=1
//! ```
//!
//! When opted in, a missing `ssh-keygen` is a failure rather than a skip: the
//! host key is generated by OpenSSH's own tool, and a lane that quietly skipped
//! its peer would report password coverage it never ran. No `sshd` is required.

#![cfg(all(feature = "ssh", unix))]

use std::{
    fmt::Write as _,
    fs::OpenOptions,
    io::Read,
    net::{Ipv4Addr, SocketAddr, TcpListener},
    path::{Path, PathBuf},
    sync::{Arc, Mutex},
    thread,
    time::Duration,
};

use neotales_docker::{DockerClient, ErrorKind, ManagedSshEstablishmentFailure};
use neotales_ssh::{
    OpenSshPrivateKey,
    auth::{ServerAuthPolicy, authenticate_server},
    hostkey::Ed25519Signer,
    known_hosts,
    server::ServerConfig,
    session::{ServerSessions, SessionDecision, SessionEvent, SessionRequest},
};

const OPT_IN: &str = "NEOTALES_DOCKER_SSH_PASSWORD_ENDPOINT";
const REQUEST_TIMEOUT: Duration = Duration::from_secs(10);
const RESPONSE: &[u8] =
    b"HTTP/1.1 200 OK\r\nApi-Version: 1.55\r\nContent-Length: 2\r\nConnection: close\r\n\r\nOK";

/// Returns true only when the lane's explicit opt-in is present.
///
/// Called before any directory, listener, key, or server exists, so the default
/// gate pays for one environment lookup and nothing else.
fn opted_in() -> bool {
    if std::env::var(OPT_IN).as_deref() != Ok("1") {
        eprintln!("skipping managed SSH password endpoint: set {OPT_IN}=1");
        return false;
    }
    true
}

/// Locates the OpenSSH key generator, or explains the opt-in prerequisite.
fn ssh_keygen() -> PathBuf {
    let mut directories: Vec<PathBuf> =
        std::env::var_os("PATH").map_or_default(|path| std::env::split_paths(&path).collect());
    directories.push(PathBuf::from("/usr/bin"));
    directories.push(PathBuf::from("/usr/local/bin"));
    directories
        .into_iter()
        .map(|directory| directory.join("ssh-keygen"))
        .find(|candidate| candidate.is_file())
        .unwrap_or_else(|| {
            panic!(
                "{OPT_IN}=1 requires the OpenSSH ssh-keygen tool, but it was not \
                 found on PATH or in the standard install directories"
            )
        })
}

/// Generates a fresh Ed25519 host key with OpenSSH and reads its seed.
///
/// The private key file lives in the caller's temporary directory and is only
/// read once; the signer zeroizes its working seed. Error messages never carry
/// the key path or the tool's output.
fn generated_host_signer(directory: &Path) -> Ed25519Signer {
    let key_path = directory.join("host_ed25519");
    let status = std::process::Command::new(ssh_keygen())
        .args(["-q", "-t", "ed25519", "-N", "", "-f"])
        .arg(&key_path)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .unwrap_or_else(|_| panic!("{OPT_IN}=1 could not run OpenSSH ssh-keygen"));
    assert!(
        status.success(),
        "{OPT_IN}=1 could not generate an ephemeral host key with ssh-keygen"
    );
    let text = std::fs::read_to_string(&key_path).expect("the generated host key is readable");
    let body: String = text
        .lines()
        .filter(|line| !line.starts_with("-----") && !line.starts_with("Private-key"))
        .collect();
    let decoded = known_hosts::decode_base64(body.trim())
        .expect("the generated host key contains PEM base64");
    let key = OpenSshPrivateKey::parse(&decoded, &mut [])
        .expect("the generated host key is an unencrypted OpenSSH Ed25519 key");
    let mut seed = [0_u8; 32];
    seed.copy_from_slice(
        key.seed()
            .expect("the generated host key contains an Ed25519 seed"),
    );
    Ed25519Signer::from_seed(&mut seed)
}

/// Returns a fresh password drawn from the operating system.
///
/// Hex keeps it free of whitespace and control characters. It is generated for
/// one test run and is never written to disk or printed.
fn generated_password() -> String {
    let mut bytes = [0_u8; 16];
    std::fs::File::open("/dev/urandom")
        .and_then(|mut file| file.read_exact(&mut bytes))
        .expect("the operating system provides an ephemeral password");
    let mut password = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        write!(&mut password, "{byte:02x}").expect("writing to a String cannot fail");
    }
    password
}

/// A local endpoint that serves one managed-SSH connection.
struct Endpoint {
    _directory: tempfile::TempDir,
    listener: Option<TcpListener>,
    signer: Option<Ed25519Signer>,
    known_hosts: PathBuf,
    address: SocketAddr,
}

impl Endpoint {
    /// Opens a loopback listener, generates a host key, and pins it in trust.
    fn new() -> Self {
        let directory = tempfile::tempdir().expect("a temporary endpoint directory");
        let listener = TcpListener::bind((Ipv4Addr::LOCALHOST, 0)).expect("a loopback listener");
        let address = listener.local_addr().expect("the listener address");
        let signer = generated_host_signer(directory.path());
        let known_hosts = directory.path().join("known_hosts");
        let mut file = OpenOptions::new()
            .create(true)
            .append(true)
            .open(&known_hosts)
            .expect("a writable trust file");
        known_hosts::append_plain(
            &mut file,
            "127.0.0.1",
            address.port(),
            &signer
                .public_key()
                .to_blob()
                .expect("the generated host key encodes"),
        )
        .expect("the generated host key is pinned");
        Self {
            _directory: directory,
            listener: Some(listener),
            signer: Some(signer),
            known_hosts,
            address,
        }
    }

    /// Builds a managed client that trusts this endpoint and offers `password`.
    fn client(&self, password: String) -> DockerClient {
        DockerClient::connect_ssh_managed(
            &format!("ssh://fixture@{}", self.address),
            &self.known_hosts,
        )
        .timeout(REQUEST_TIMEOUT)
        .request_deadline(Some(REQUEST_TIMEOUT))
        .password(password.into())
        .connect()
        .expect("a managed SSH client")
    }

    /// Starts the local peer and keeps the trust directory alive until the test
    /// finishes with `self`.
    fn serve(
        &mut self,
        expected_password: String,
    ) -> thread::JoinHandle<Result<ServerLog, String>> {
        let listener = self.listener.take().expect("one listener per endpoint");
        let signer = self.signer.take().expect("one signer per endpoint");
        thread::spawn(move || serve_password_endpoint(listener, signer, expected_password))
    }
}

/// What the local peer observed and answered.
#[derive(Clone, Debug, Default)]
struct ServerLog {
    events: Vec<&'static str>,
    password_attempts: usize,
}

fn record(log: &Arc<Mutex<ServerLog>>, event: &'static str) {
    log.lock()
        .expect("the server log is not poisoned")
        .events
        .push(event);
}

fn snapshot(log: &Arc<Mutex<ServerLog>>) -> ServerLog {
    log.lock().expect("the server log is not poisoned").clone()
}

/// Serves exactly one managed Engine request over one authenticated session.
#[allow(clippy::needless_pass_by_value)] // The listener is moved into the peer thread.
fn serve_password_endpoint(
    listener: TcpListener,
    signer: Ed25519Signer,
    expected_password: String,
) -> Result<ServerLog, String> {
    let log = Arc::new(Mutex::new(ServerLog::default()));
    let (peer, _) = listener
        .accept()
        .map_err(|_| "the local endpoint did not accept a connection".to_owned())?;
    peer.set_read_timeout(Some(REQUEST_TIMEOUT))
        .and_then(|()| peer.set_write_timeout(Some(REQUEST_TIMEOUT)))
        .map_err(|_| "the local endpoint could not bound its socket".to_owned())?;
    let mut transport = ServerConfig::new(signer)
        .connect(peer)
        .map_err(|_| "the local endpoint failed its SSH handshake".to_owned())?;
    let password_log = Arc::clone(&log);
    let policy = ServerAuthPolicy::new(2)
        .map_err(|_| "the local endpoint rejected its authentication policy".to_owned())?
        .with_password_callback(move |password| {
            let accepted = password == expected_password;
            let mut log = password_log.lock().expect("the server log is not poisoned");
            log.password_attempts += 1;
            log.events.push(if accepted {
                "password-accepted"
            } else {
                "password-rejected"
            });
            accepted
        });
    if authenticate_server(&mut transport, &policy).is_err() {
        record(&log, "auth-ended");
        return Ok(snapshot(&log));
    }
    record(&log, "authenticated");
    let mut sessions = ServerSessions::with_policy(transport, |request| match request {
        SessionRequest::Exec { command } if command == b"docker system dial-stdio" => {
            SessionDecision::accept(0)
        }
        _ => SessionDecision::reject(),
    });
    let session = match sessions.dispatch_one() {
        Ok(SessionEvent::Opened { session }) => {
            record(&log, "session-opened");
            session
        }
        _ => return Err("the local endpoint did not open a session".to_owned()),
    };
    match sessions.dispatch_one() {
        Ok(SessionEvent::Request { accepted: true, .. }) => record(&log, "exec-accepted"),
        _ => return Err("the local endpoint did not accept dial-stdio".to_owned()),
    }
    let mut request = Vec::new();
    loop {
        match sessions.dispatch_one() {
            Ok(SessionEvent::Data { data, .. }) => {
                request.extend_from_slice(&data);
                if request.windows(4).any(|window| window == b"\r\n\r\n") {
                    break;
                }
            }
            Ok(_) => {}
            Err(_) => return Err("the local endpoint failed while reading the request".to_owned()),
        }
    }
    if !request.starts_with(b"GET /")
        || !request
            .windows(b"/_ping HTTP/1.1\r\n".len())
            .any(|window| window == b"/_ping HTTP/1.1\r\n")
    {
        return Err("the local endpoint received an unexpected Engine request".to_owned());
    }
    record(&log, "ping-request");
    sessions
        .send_data(session, RESPONSE)
        .map_err(|_| "the local endpoint could not answer the request".to_owned())?;
    record(&log, "ping-answered");
    let _ = sessions.send_exit_status(session);
    let _ = sessions.send_eof(session);
    let _ = sessions.send_close(session);
    Ok(snapshot(&log))
}

fn join(server: thread::JoinHandle<Result<ServerLog, String>>) -> Result<ServerLog, String> {
    server
        .join()
        .map_err(|_| "the local endpoint thread panicked".to_owned())?
}

#[tokio::test]
#[ignore = "opt-in: NEOTALES_DOCKER_SSH_PASSWORD_ENDPOINT=1"]
async fn server_accepts_the_generated_password_and_the_client_receives_ping() {
    if !opted_in() {
        return;
    }
    let mut endpoint = Endpoint::new();
    let password = generated_password();
    let server = endpoint.serve(password.clone());
    let client = endpoint.client(password);
    let ping = tokio::time::timeout(REQUEST_TIMEOUT, client.ping())
        .await
        .expect("the managed password request did not settle")
        .expect("the local endpoint rejected the generated password");
    assert_eq!(
        ping.api_version.as_deref(),
        Some("1.55"),
        "the client did not receive the endpoint's answer: {ping:?}"
    );
    let log = join(server).expect("the local endpoint reported a failure");
    assert_eq!(log.password_attempts, 1, "server log: {log:?}");
    assert_eq!(
        log.events,
        [
            "password-accepted",
            "authenticated",
            "session-opened",
            "exec-accepted",
            "ping-request",
            "ping-answered",
        ],
        "server log: {log:?}"
    );
    eprintln!("server log: {log:?}");
    eprintln!(
        "client received /_ping api_version={:?}",
        ping.api_version.as_deref()
    );
}

#[tokio::test]
#[ignore = "opt-in: NEOTALES_DOCKER_SSH_PASSWORD_ENDPOINT=1"]
async fn server_rejection_is_typed_and_does_not_echo_the_credential() {
    if !opted_in() {
        return;
    }
    let mut endpoint = Endpoint::new();
    let server_password = generated_password();
    let mut client_password = generated_password();
    while client_password == server_password {
        client_password = generated_password();
    }
    let server = endpoint.serve(server_password);
    let client = endpoint.client(client_password.clone());
    let error = tokio::time::timeout(REQUEST_TIMEOUT, client.ping())
        .await
        .expect("the managed password request did not settle")
        .expect_err("the local endpoint accepted the wrong password");
    assert_eq!(error.kind(), ErrorKind::Transport);
    assert!(
        error.is_managed_ssh_authentication_rejected(),
        "unexpected classification: {error}"
    );
    assert_eq!(
        error.managed_ssh_establishment_failure(),
        Some(ManagedSshEstablishmentFailure::AuthenticationRejected)
    );
    for rendered in [format!("{error}"), format!("{error:?}")] {
        assert!(
            !rendered.contains(&client_password),
            "the managed diagnostic echoed the credential: {rendered}"
        );
    }
    let log = join(server).expect("the local endpoint reported a failure");
    assert_eq!(log.password_attempts, 1, "server log: {log:?}");
    assert_eq!(
        log.events,
        ["password-rejected", "auth-ended"],
        "server log: {log:?}"
    );
    eprintln!("server log: {log:?}");
    eprintln!("client received typed rejection: {error}");
}
